export function translate(language: Language, key: string, values: object = {}): string {
  const dictionary: Readonly<Record<string, string>> = dictionaries[language];
  const template = dictionary[key] ?? en[key as TranslationKey] ?? key;
  const interpolationValues = values as Readonly<Record<string, unknown>>;
  return template.replace(/{{\s*([\w]+)\s*}}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(interpolationValues, name) ? String(interpolationValues[name]) : placeholder,
  );
}

