export type TranslationKey = keyof typeof ru;

const dictionaries: Readonly<Record<Language, Readonly<Record<TranslationKey, string>>>> = {
  ru,
  en,
  kk: { ...en, ...miniappLocaleOverlays.kk },
  uz: { ...en, ...miniappLocaleOverlays.uz },
  tk: { ...en, ...miniappLocaleOverlays.tk },
  'zh-CN': { ...en, ...miniappLocaleOverlays['zh-CN'] },
  hi: { ...en, ...miniappLocaleOverlays.hi },
};

export function translate(language: Language, key: TranslationKey, values?: Record<string, string | number>): string {
  let value: string = dictionaries[language][key];
  for (const [name, replacement] of Object.entries(values ?? {})) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function accommodationLabel(language: Language, type: AccommodationType): string {
  return translate(language, type);
}

export function stageLabel(language: Language, stage: string): string {
  const normalized = stage.toLowerCase().replaceAll('-', '_');
  if (['preparing', 'pre_arrival', 'before_arrival'].includes(normalized)) {
    return translate(language, 'stagePreparing');
  }
  if (['first_days', 'first_3_days', 'first_three_days', 'arrival'].includes(normalized)) {
    return translate(language, 'stageFirstDays');
  }
  if (['first_week', 'week_1'].includes(normalized)) {
    return translate(language, 'stageFirstWeek');
  }
  if (['first_month', 'first_30_days', 'remaining_days', 'month_1'].includes(normalized)) {
    return translate(language, 'stageFirstMonth');
  }
  return stage.replaceAll('_', ' ');
}
